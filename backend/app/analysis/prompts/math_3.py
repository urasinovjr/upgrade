def recognize_messages(pages: list[PageImage], tasks: list[TaskInput]) -> list[dict]:
    messages = math_2.recognize_messages(pages, tasks)
    messages[0]["content"] = RECOGNIZE_SYSTEM
    mapping = [{"task_id": task.id, "solution_file_ids": task.solution_file_ids} for task in tasks]
    messages[1]["content"].append({"type": "text", "text": json.dumps(mapping, ensure_ascii=False)})
    for number, page in enumerate(pages, 1):
        messages[1]["content"].append(
            {"type": "text", "text": f"Страница {number}: файл {page.file_id}"}
        )
    return messages


def review_messages(tasks: list[ReviewTask], conditions: list[ConditionImage]) -> list[dict]:
    payload = [
        {
            **task.model_dump(),
            "condition_is_image": any(
                item.task_id == task.id and item.kind == "condition" for item in conditions
            ),
        }
        for task in tasks
    ]
    content = [
        {
            "type": "text",
            "text": (
                f"Темы:\n{math_2.topic_text()}\nТипы:\n{math_2.type_text()}\n"
                f"Задачи:\n{json.dumps(payload, ensure_ascii=False)}"
            ),
        }
    ]
    for item in conditions:
        label = "Условие" if item.kind == "condition" else "Решение"
        content.append(
            {"type": "text", "text": f"{label} задачи {item.task_id}, страница {item.image.page}"}
        )
        content.append({"type": "image_url", "image_url": {"url": math_2.data_url(item.image)}})
    return [{"role": "system", "content": REVIEW_SYSTEM}, {"role": "user", "content": content}]
